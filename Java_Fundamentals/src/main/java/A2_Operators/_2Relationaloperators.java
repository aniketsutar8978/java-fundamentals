package A2_Operators;

public class _2Relationaloperators {        
	
	// Relational operators are used to check relation between tow operands 
	// Relational operators are used to check only one condition
	// The output of relational operators will be in boolean data type.
	
	public static void main(String[] args)
	{
		int a=10, y=100, c=150;
		
		System.out.println("a is greater than "+y+" = "+(a>y));
		System.out.println("a is less than "+y+" = "+(a<y));
		System.out.println("a is greater than equals to "+y+" = "+(a>=y));
		System.out.println("a is less than equal to "+y+" = "+(a<=y));
		System.out.println("a is equals to equal "+y+" = "+(a==y));
		System.out.println("a is not equals to "+y+" = "+(a!=y));
		
	
	  
	}

}
